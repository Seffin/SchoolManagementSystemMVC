using Microsoft.EntityFrameworkCore;
using SchoolManagementSystemMVC.Data;
using SchoolManagementSystemMVC.Models;

namespace SchoolManagementSystemMVC.Services
{
    public interface IStudentService
    {
        Task<int> CreateStudentAsync(Student student);
        Task<List<Student>> GetAllStudentsAsync();
        Task<bool> ValidateLoginAsync(string username, string password);
    }

    public class StudentService : IStudentService
    {
        private readonly ApplicationDbContext _context;

        public StudentService(ApplicationDbContext context)
        {
            _context = context;
        }

        public async Task<int> CreateStudentAsync(Student student)
        {
            _context.Students.Add(student);
            await _context.SaveChangesAsync();
            return student.StudentId; // Auto-generated by database
        }

        public async Task<List<Student>> GetAllStudentsAsync()
        {
            return await _context.Students
                .Include(s => s.Qualifications)
                .OrderBy(s => s.StudentId)
                .ToListAsync();
        }

        public async Task<bool> ValidateLoginAsync(string username, string password)
        {
            if (string.IsNullOrEmpty(username) || string.IsNullOrEmpty(password))
                return false;

            return await _context.Students
                .AnyAsync(s => s.Username == username && s.Password == password);
        }
    }
}